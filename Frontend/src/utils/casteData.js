// All unique castes combined for fallback or open search
export const allCommonCastes = Array.from(
  new Set(Object.values(castesByLanguage).flat())
).sort();

export const getCastesForLanguage = (language, includeNoPreference = true) => {
  const languageCastes = language && castesByLanguage[language]
    ? castesByLanguage[language]
    : allCommonCastes;

  if (includeNoPreference) {
    return ["No Preference", ...languageCastes];
  }
  return languageCastes;
};
